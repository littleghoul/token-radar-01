// Token Radar's model: one sealed snapshot in, one ranked board out.
//
// The board ranks every protocol that records no token of its own and is not a
// wrapped, staked or bridged product of a token that already trades. That is the
// whole test: the snapshot's watchlist is the floor (40 protocols at or above the
// $50M floor), and the early radar adds every other protocol that passes the same
// test, above or below the floor. A wrapped product such as WBTC, a staked product
// such as Binance staked ETH, a bridge, a CEX or a versioned pool (a name ending
// in V2, 2.0 and the like) never ranks: its token already trades, or it is a pool
// of another protocol, so there is no launch of its own to find.
//
// Implied value follows only from the snapshot's own figures, one function for
// every row, no name ever special-cased:
//
//   base       = tvl_usd x BASE_MULTIPLE
//   growth     = clamp(change_7d, -50, 150) per cent
//   growthMult = 1 + (growth / 100) x GROWTH_WEIGHT
//   maturity   = 0.5 + min(age_days, 1460) / 1460 x 0.5   (age_days unknown: 365)
//   chains     = 1 + 0.03 x min(chains.length, 8)
//   implied    = max(1, round(base x growthMult x maturity x chains))
//
// TVL is the size of the business a token would price. Seven-day growth is the
// direction it is moving. Age is how long it has run with no token: the longer a
// protocol of this size has waited, the more its launch is worth waiting for.
// Chains is reach: a protocol live on more chains has more users to issue to.
// The constants are stated in the dashboard and changeable in one place.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, as the dashboard states them. */
export interface ModelConstants {
  base_multiple: number;
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
  chain_weight: number;
  chain_cap: number;
}

